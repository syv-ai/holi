/**
 * `holi` — the command the agent types to ask Holi to do something.
 *
 * A generated shell script rather than a shipped binary, for the reasons
 * `holi-google` is one (D67): no build step or packaging entry, readable by the
 * person whose machine it is on, and it re-reads `$HOLI_HOOK_PORT` /
 * `$HOLI_HOOK_TOKEN` at every invocation — so it survives an app restart, which
 * moves the ephemeral port. Baking either in produces a CLI that works exactly
 * until Holi is restarted once, and then fails in a way that looks like a
 * network bug.
 *
 * It exists because slice 1 left the agent writing an app blind: it could not
 * see the result, so its only move was to ask the user to go and look. `app
 * open` closes that loop.
 *
 * `holi-google` sorts its subcommands by reversibility, because some of them
 * reach another person. **All three of these are reversible** — opening a tab,
 * scaffolding a directory, rewriting a file Holi itself wrote and can rewrite
 * again — which is why none of them is gated. That is the same rule (D70)
 * reaching the opposite conclusion, not a different one.
 */
import { chmod, mkdir, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'

const SCRIPT = `#!/bin/sh
# holi — ask the running Holi app to do something.
# Generated by Holi. Talks to the app over 127.0.0.1 and holds no secret of
# yours: the port and the token come from the environment Holi started you with.
#
# Every command here is reversible or read-only, which is why none of them
# asks first:
#   app open <id>            open the app's tab (you can close it)
#   app init <id>            scaffold a new app directory (you can delete it)
#   seed refresh [path]      rewrite the managed files Holi itself wrote
#   pdf comments <path>      print a PDF's comments (reads, changes nothing)
#
# If this says Holi is not running, it is not running, or you are in a shell it
# did not start.
set -eu

if [ -z "\${HOLI_HOOK_PORT:-}" ] || [ -z "\${HOLI_HOOK_TOKEN:-}" ]; then
  echo "holi: Holi is not running, or this shell was not started by it." >&2
  exit 1
fi

base="http://127.0.0.1:\$HOLI_HOOK_PORT"

usage() {
  cat >&2 <<'USAGE'
usage: holi <command>

  app open <id>                 open a finished app in a tab
  app init <id>                 scaffold .holi/apps/<id>/ with a manifest
  seed refresh [path] [--force] rewrite the managed files Holi wrote
  pdf comments <path> [--json]  print a vault PDF's comments: page, mark,
                                marked text, author, dates and replies

An app is finished when it has app.yaml next to index.html. Write the manifest
LAST: it is what registers the app, so the tab never opens onto half a page.
USAGE
  exit 2
}

# POST one operation. The token rides in the query string (one auth mechanism,
# the same one the turn-signal hooks use); every argument rides in the body so
# curl encodes it. Hand-rolling percent-encoding in POSIX sh is how a path with
# a space silently becomes a different path.
post() {
  op="\$1"; shift
  curl -sS --fail-with-body -X POST "\$base/\$op?t=\$HOLI_HOOK_TOKEN" "\$@"
}

cmd="\${1:-}"
[ $# -gt 0 ] && shift

case "\$cmd" in
  app)
    sub="\${1:-}"
    [ $# -gt 0 ] && shift
    case "\$sub" in
      open)
        [ $# -ge 1 ] || { echo "holi app open <id>" >&2; exit 2; }
        post app/open --data-urlencode "id=\$1"
        ;;
      init)
        [ $# -ge 1 ] || { echo "holi app init <id>" >&2; exit 2; }
        post app/init --data-urlencode "id=\$1"
        ;;
      *) usage ;;
    esac
    ;;
  seed)
    sub="\${1:-}"
    [ $# -gt 0 ] && shift
    case "\$sub" in
      refresh)
        # Options are parsed into variables FIRST, then the curl arguments are
        # built: building them with \`set --\` while still looping over \$@
        # rewrites the very list being iterated, and the loop reads its own
        # output. (holi-google reschedule carries the same comment, and the
        # same scar.)
        path=""; force=""
        while [ $# -gt 0 ]; do
          case "\$1" in
            --force) force=true; shift ;;
            -*) echo "holi seed refresh: unknown option \$1" >&2; exit 2 ;;
            *) path="\$1"; shift ;;
          esac
        done
        set -- --data-urlencode "force=\${force:-false}"
        [ -n "\$path" ] && set -- "\$@" --data-urlencode "path=\$path"
        post seed/refresh "\$@"
        ;;
      *) usage ;;
    esac
    ;;
  pdf)
    sub="\${1:-}"
    [ $# -gt 0 ] && shift
    case "\$sub" in
      comments)
        path=""; json=""
        while [ $# -gt 0 ]; do
          case "\$1" in
            --json) json=true; shift ;;
            -*) echo "holi pdf comments: unknown option \$1" >&2; exit 2 ;;
            *) path="\$1"; shift ;;
          esac
        done
        [ -n "\$path" ] || { echo "holi pdf comments <path> [--json]" >&2; exit 2; }
        # Not \`post\`: the answer is the output itself, so the status decides
        # where it goes (stdout, or stderr and a failing exit) rather than
        # curl's exit code. The body goes through a file so that nothing about
        # its contents, a trailing newline included, is lost on the way.
        body=\$(mktemp)
        trap 'rm -f "\$body"' EXIT
        code=\$(curl -sS -X POST -o "\$body" -w '%{http_code}' \\
          "\$base/pdf/comments?t=\$HOLI_HOOK_TOKEN" \\
          --data-urlencode "path=\$path" --data-urlencode "json=\${json:-false}") || exit 1
        if [ "\$code" = 200 ]; then
          cat "\$body"; echo
        else
          echo "holi pdf comments: \$(cat "\$body")" >&2
          exit 1
        fi
        ;;
      *) usage ;;
    esac
    ;;
  *) usage ;;
esac
`

/**
 * `holi-statusline` — what a session's footer prints, asked of Holi.
 *
 * **It parses nothing.** Claude Code writes its status JSON to this script's
 * stdin, the script posts that straight through, and Holi answers with the line
 * to print. The alternative was picking fields out of JSON in POSIX sh: `jq` is
 * not installed on a stock macOS, and hand-rolled `sed` over another program's
 * output is a parser that breaks on the version that adds a field.
 *
 * It also means main SEES the status, which is the point: the model and the
 * context reading go on the wire with the session list, and `session_name`
 * carries the title Claude Code's own small-model pass wrote for the session.
 *
 * Silent on every failure. A status line that printed `curl: (7) failed to
 * connect` into the footer of every session would be worse than an empty row,
 * and Holi not running is an ordinary state for a `claude` the user started
 * themselves.
 */
const STATUSLINE_SCRIPT = `#!/bin/sh
# holi-statusline — ask the running Holi app what this session's footer says.
# Generated by Holi. Reads Claude Code's status JSON on stdin and prints one
# line. Holds no secret of yours: the port and the token come from the
# environment Holi started you with.
set -eu

[ -n "\${HOLI_HOOK_PORT:-}" ] || exit 0
[ -n "\${HOLI_HOOK_TOKEN:-}" ] || exit 0

curl -sS --max-time 2 -X POST \\
  -H 'content-type: application/json' \\
  --data-binary @- \\
  "http://127.0.0.1:\$HOLI_HOOK_PORT/statusline?t=\$HOLI_HOOK_TOKEN" 2>/dev/null || exit 0
`

/**
 * Write the script and make it executable. Returns its absolute path, which
 * becomes `$HOLI_BIN` in the agent's env.
 *
 * Rewritten on every launch rather than written once: it is generated content,
 * so an app update must not leave an older copy in place.
 */
export async function installHoliCli(userDataDir: string): Promise<string> {
  const path = join(userDataDir, 'bin', 'holi')
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, SCRIPT, { mode: 0o755 })
  // `writeFile`'s mode is ignored when the file already exists.
  await chmod(path, 0o755)
  await installStatusLine(userDataDir)
  return path
}

export { SCRIPT as HOLI_CLI_SCRIPT }

/** The status-line script, beside `holi` and on the same terms: regenerated on
 *  every launch, executable, and named in the vault config directory's
 *  `statusLine` setting rather than found on PATH — Claude Code runs that
 *  command in a shell of its own, and an absolute path cannot be shadowed. */
export async function installStatusLine(userDataDir: string): Promise<string> {
  const path = join(userDataDir, 'bin', 'holi-statusline')
  await mkdir(dirname(path), { recursive: true })
  await writeFile(path, STATUSLINE_SCRIPT, { mode: 0o755 })
  await chmod(path, 0o755)
  return path
}

/** Where `installStatusLine` puts it, without writing it. The config-directory
 *  seed needs the path on every spawn; the file itself is written once a launch. */
export function statusLinePath(userDataDir: string): string {
  return join(userDataDir, 'bin', 'holi-statusline')
}
