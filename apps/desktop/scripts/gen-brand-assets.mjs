// Regenerate `src/main/agent/templates/_brand/binary-assets.generated.ts` from
// the raw brand binaries (Raleway fonts + logo). Run after replacing any of them:
//
//   node scripts/gen-brand-assets.mjs
//
// Typst is downloaded, not bundled, so there is no binary-resource pipeline to
// piggyback on; base64 embedded in a TS module bundles into the main JS exactly
// like the ?raw text seeds and is importable by the node test project.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const brandDir = join(here, '..', 'src', 'main', 'agent', 'templates', '_brand')
const VAULT_PREFIX = '.holi/document-templates/_brand'

// vault-relative path -> absolute source file
const files = [
  ...readdirSync(join(brandDir, 'fonts'))
    .filter((f) => f.endsWith('.ttf'))
    .sort()
    .map((f) => [`${VAULT_PREFIX}/fonts/${f}`, join(brandDir, 'fonts', f)]),
  [`${VAULT_PREFIX}/logo.png`, join(brandDir, 'logo.png')],
]

const entries = files
  .map(([rel, abs]) => `  ${JSON.stringify(rel)}: ${JSON.stringify(readFileSync(abs).toString('base64'))},`)
  .join('\n')

const out = `// @generated by scripts/gen-brand-assets.mjs — do not edit by hand.
// Raw brand binaries (Raleway fonts + logo, OFL) base64-encoded so they bundle
// into the main JS and seed into each vault's .holi/document-templates/_brand/.
export const BRAND_BINARIES: Record<string, string> = {
${entries}
}
`

const dest = join(brandDir, 'binary-assets.generated.ts')
writeFileSync(dest, out)
console.log(`wrote ${dest} (${files.length} files)`)
